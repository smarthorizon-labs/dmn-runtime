/**
 * Differential testing against Apache KIE Drools.
 *
 * Original work. Drools is the
 * project's reference where the DMN specification is ambiguous, which is only
 * meaningful if "what Drools does" is executable rather than asserted.
 *
 * The harness runs in two halves so that CI never needs a JVM:
 *
 * 1. `export` writes the cases — model path and inputs, in the shared wire
 *    format — for the Java tool in `tools/drools-reference`.
 * 2. `compare` reads the recorded Drools results back and puts them beside our
 *    own, together with what the TCK expects.
 *
 * The third column is what makes the report actionable. Knowing that two
 * engines disagree is mildly interesting; knowing which of them the TCK agrees
 * with tells you who is wrong.
 */

import { NOT_EVALUATED_CODES } from '@smarthorizon-labs/dmn-feel';

import {
  compileFor,
  decodeInputs,
  discoverTestFiles,
  invoke,
  type RunOptions,
} from './runner.js';
import { encodeFeel, wireEquals, type WireValue } from './wire.js';

export interface DifferentialCase {
  /** `<level>/<case>/<file>/<testCase>`. */
  readonly id: string;
  /** Model path relative to the TCK's `TestCases` directory. */
  readonly model: string;
  /**
   * Set when the case invokes a decision service rather than evaluating the
   * whole model. Both engines must honour it, or the recorded reference is
   * from the wrong API and the comparison is meaningless.
   */
  readonly invocable?: { readonly type: string; readonly name: string };
  readonly inputs: Readonly<Record<string, WireValue>>;
  readonly decisions: readonly string[];
}

export interface CaseExport {
  readonly $comment: string;
  readonly cases: readonly DifferentialCase[];
}

/** Recorded reference output: case id, then decision name, then value. */
export type ReferenceResults = Readonly<Record<string, Readonly<Record<string, WireValue>>>>;

export function exportCases(options: RunOptions): CaseExport {
  const cases: DifferentialCase[] = [];

  for (const discovered of discoverTestFiles(options)) {
    if (discovered.suite === undefined) {
      continue;
    }

    for (const testCase of discovered.suite.cases) {
      const inputs: Record<string, WireValue> = {};
      for (const [name, value] of testCase.inputs) {
        inputs[name] = value;
      }

      cases.push({
        id: `${discovered.prefix}/${testCase.id}`,
        model: discovered.modelPath,
        ...(testCase.invocable === undefined ? {} : { invocable: testCase.invocable }),
        inputs,
        // Deduplicated: a result node may appear more than once per case.
        decisions: [...new Set(testCase.results.map((result) => result.name))],
      });
    }
  }

  return {
    $comment:
      'Inputs for the Drools reference run. Generated by `npm run diff:export`; ' +
      'consumed by tools/drools-reference. Both engines are handed these exact values.',
    cases,
  };
}

export type Agreement =
  /** Both engines produced the same value. */
  | 'AGREE'
  /** Both produced a value, and they differ. This is the interesting one. */
  | 'DIFFER'
  /** Both engines reported a failure. */
  | 'BOTH_ERROR'
  /** Drools evaluated it; this runtime cannot yet. */
  | 'OURS_UNSUPPORTED'
  /** This runtime evaluated it; Drools reported an error. */
  | 'DROOLS_ERROR'
  /** No reference value was recorded for this key. */
  | 'NOT_RECORDED';

/** Which engine, if either, the TCK expectation backs. */
export type Arbitration = 'BOTH' | 'OURS' | 'DROOLS' | 'NEITHER' | 'NO_EXPECTATION';

export interface Divergence {
  /** `<level>/<case>/<file>/<testCase>/<resultNode>`. */
  readonly key: string;
  readonly agreement: Agreement;
  readonly arbitration: Arbitration;
  readonly ours: WireValue;
  readonly drools: WireValue;
  readonly tck: WireValue;
}

export interface DifferentialSummary {
  readonly results: readonly Divergence[];
  readonly counts: Readonly<Record<Agreement, number>>;
  /** Divergences where the TCK backs Drools: our defects, in priority order. */
  readonly ourDefects: readonly Divergence[];
  /** Divergences the TCK backs neither engine on: the expectation is suspect. */
  readonly unexplained: readonly Divergence[];
  /** Divergences where the TCK backs us over Drools. */
  readonly droolsDefects: readonly Divergence[];
}

export function compareToReference(
  options: RunOptions,
  reference: ReferenceResults,
): DifferentialSummary {
  const results: Divergence[] = [];

  for (const discovered of discoverTestFiles(options)) {
    if (discovered.suite === undefined) {
      continue;
    }

    const loaded = compileFor(discovered);

    for (const testCase of discovered.suite.cases) {
      const caseId = `${discovered.prefix}/${testCase.id}`;
      const recorded = reference[caseId];

      const ourValues = evaluateCase(loaded, testCase);

      for (const result of testCase.results) {
        const ours = ourValues.get(result.name) ?? {
          type: 'error' as const,
          message: 'no result',
        };
        const drools = recorded?.[result.name];

        if (drools === undefined) {
          results.push({
            key: `${caseId}/${result.name}`,
            agreement: 'NOT_RECORDED',
            arbitration: 'NO_EXPECTATION',
            ours,
            drools: { type: 'error', message: 'not recorded' },
            tck: result.expected,
          });
          continue;
        }

        results.push({
          key: `${caseId}/${result.name}`,
          agreement: classify(ours, drools),
          arbitration: arbitrate(ours, drools, result.expected, result.errorResult),
          ours,
          drools,
          tck: result.expected,
        });
      }
    }
  }

  const counts = {
    AGREE: 0,
    DIFFER: 0,
    BOTH_ERROR: 0,
    OURS_UNSUPPORTED: 0,
    DROOLS_ERROR: 0,
    NOT_RECORDED: 0,
  };

  for (const divergence of results) {
    counts[divergence.agreement]++;
  }

  const differing = results.filter((divergence) => divergence.agreement === 'DIFFER');

  return {
    results,
    counts,
    ourDefects: differing.filter((divergence) => divergence.arbitration === 'DROOLS'),
    unexplained: differing.filter((divergence) => divergence.arbitration === 'NEITHER'),
    droolsDefects: differing.filter((divergence) => divergence.arbitration === 'OURS'),
  };
}

function evaluateCase(
  loaded: ReturnType<typeof compileFor>,
  testCase: {
    inputs: ReadonlyMap<string, WireValue>;
    results: readonly { name: string }[];
    invocable?: { type: string; name: string };
  },
): Map<string, WireValue> {
  const values = new Map<string, WireValue>();

  if ('error' in loaded) {
    for (const result of testCase.results) {
      values.set(result.name, { type: 'error', message: `model load: ${loaded.error}` });
    }
    return values;
  }

  const { context, unrepresentable } = decodeInputs(testCase.inputs);

  if (unrepresentable !== undefined) {
    for (const result of testCase.results) {
      values.set(result.name, {
        type: 'unsupported',
        detail: `input ${unrepresentable} has an unsupported type`,
      });
    }
    return values;
  }

  let evaluation;
  try {
    evaluation = invoke(loaded.compiled, testCase, context);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    for (const result of testCase.results) {
      values.set(result.name, { type: 'error', message });
    }
    return values;
  }

  for (const result of testCase.results) {
    const decision = evaluation.decisions.get(result.name);

    if (decision === undefined) {
      values.set(result.name, { type: 'error', message: 'no such decision' });
      continue;
    }

    if (decision.failed) {
      values.set(result.name, {
        type: 'error',
        message: decision.messages[0] ?? 'decision failed',
      });
      continue;
    }

    // The same rule the TCK judge applies: any diagnostic meaning "this was
    // not evaluated" makes the result unusable as a comparison, whatever value
    // happened to come out of it.
    const unsupported = decision.warnings.find((warning) =>
      NOT_EVALUATED_CODES.has(warning.code),
    );

    values.set(
      result.name,
      unsupported === undefined
        ? encodeFeel(decision.value)
        : { type: 'unsupported', detail: unsupported.message },
    );
  }

  return values;
}

function classify(ours: WireValue, drools: WireValue): Agreement {
  const oursFailed = ours.type === 'error' || ours.type === 'unsupported';
  const droolsFailed = drools.type === 'error';

  // Under null propagation (ADR-0005) a failed decision *is* a null one, so a
  // null here and a raised error there are the same observation reported in
  // two engines' idioms. Counting them as disagreement would have made 769
  // comparisons look like divergences when nothing diverged.
  if (droolsFailed && !oursFailed && ours.type === 'null') {
    return 'BOTH_ERROR';
  }

  if (oursFailed && droolsFailed) {
    return 'BOTH_ERROR';
  }

  if (oursFailed) {
    return 'OURS_UNSUPPORTED';
  }

  if (droolsFailed) {
    return 'DROOLS_ERROR';
  }

  return wireEquals(ours, drools, 'exact') ? 'AGREE' : 'DIFFER';
}

/**
 * Decides which engine the TCK expectation supports.
 *
 * The TCK is compared under the recorded-precision policy, because its
 * expectations are written down with fewer digits than either engine produces.
 */
function arbitrate(
  ours: WireValue,
  drools: WireValue,
  tck: WireValue,
  errorExpected: boolean,
): Arbitration {
  if (errorExpected) {
    const oursErrored = ours.type === 'error';
    const droolsErrored = drools.type === 'error';

    if (oursErrored && droolsErrored) return 'BOTH';
    if (oursErrored) return 'OURS';
    if (droolsErrored) return 'DROOLS';
    return 'NEITHER';
  }

  const oursMatches = wireEquals(ours, tck, 'recorded');
  const droolsMatches = wireEquals(drools, tck, 'recorded');

  if (oursMatches && droolsMatches) return 'BOTH';
  if (oursMatches) return 'OURS';
  if (droolsMatches) return 'DROOLS';
  return 'NEITHER';
}
